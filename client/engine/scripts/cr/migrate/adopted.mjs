/* THE ADOPTION TABLE — step 1a input of the CR-only migration.
 *
 *   node client/engine/scripts/cr/migrate/adopted.mjs [--check]
 *     → client/engine/scripts/cr/migrate/adopted.json   (COMMITTED data)
 *
 * For every `## R<n>` heading in the register: the date it was adopted (the
 * first commit that added its heading line, walked with `git log --reverse -p`
 * over BOTH paths the register has had — `digital-client/docs/` before the
 * 2026-08-30 reorg, `client/docs/` after; `-S` over the new path alone returns
 * the reorg date for every older ruling), and the question-sheet back-pointer
 * its text names (`questions-round27 Q2`), which test 238 reads after the
 * register is gone.
 *
 * The table is committed so the migration never depends on git history again:
 * absorb.mjs reads it, and refuses a ruling it does not list. Re-run this only
 * if a ruling is added before the migration lands. `--check` exits 1 when the
 * register holds a ruling the table lacks (or a date that disagrees). */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseRulings } from '../extract.mjs';
import { headingDates } from './audit.mjs';

const HERE = fileURLToPath(new URL('.', import.meta.url));
export const ADOPTED_JSON = join(HERE, 'adopted.json');
const SHEET_RE = /questions-round(\d+)(?:\.md)? Q(\d+)/g;

export function buildAdopted() {
  const dates = headingDates();
  const out = {};
  const missing = [];
  for (const r of parseRulings()) {
    const d = dates[r.id];
    if (!d) { missing.push(r.id); continue; }
    const sheets = [...new Set([...`${r.heading}\n${r.body}`.matchAll(SHEET_RE)].map((m) => `questions-round${m[1]} Q${m[2]}`))];
    out[r.id] = { adopted: d.date, commit: d.commit, ...(sheets.length ? { from: sheets.join(', ') } : {}) };
  }
  return { rulings: out, missing };
}

export function readAdopted() {
  if (!existsSync(ADOPTED_JSON)) throw new Error(`${ADOPTED_JSON} is missing: run adopted.mjs on a checkout that still has the register and its history`);
  return JSON.parse(readFileSync(ADOPTED_JSON, 'utf8')).rulings;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { rulings, missing } = buildAdopted();
  if (process.argv.includes('--check')) {
    const have = readAdopted();
    const bad = Object.entries(rulings).filter(([id, v]) => have[id]?.adopted !== v.adopted).map(([id]) => id);
    if (bad.length || missing.length) { console.log(`adopted.json is stale: ${[...bad, ...missing].join(', ')}`); process.exit(1); }
    console.log(`adopted.json covers all ${Object.keys(rulings).length} rulings`);
  } else {
    if (missing.length) { console.error(`no adding commit found for ${missing.join(', ')}`); process.exit(1); }
    writeFileSync(ADOPTED_JSON, JSON.stringify({
      _doc: 'Generated by adopted.mjs from the register and its git history (both paths). ruling → {adopted: first commit adding its heading, commit, from?: the question sheet it answers}. Committed so the migration never reads git history again.',
      rulings,
    }, null, 1) + '\n');
    console.log(`wrote ${Object.keys(rulings).length} rulings to ${ADOPTED_JSON}`);
  }
}
