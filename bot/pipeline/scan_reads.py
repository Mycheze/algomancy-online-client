"""scan_reads.py — which scan FILE each scan reader last read, by content hash.

The four scan readers (build_anchors, classify_complexity, read_text_boxes,
read_card_faces) each write data read off the card scans. Replacing a scan
does not re-run them, and the data they wrote stays the old picture's: each
scan swap until 2026-11-06 left rows stale (BL-70: Torrential Reclamation's
type bar, five complexity scores), and no test could tell.

So each reader, when it writes its output, also records here a short sha256 of
every scan it opened — template scans included, since a changed template moves
every row. `client/engine/test/1159-scan-reads-current.test.ts` hashes
data/cards/*.jpg and fails naming each card whose scan differs from what a
reader read, and which reader to re-run.

Usage in a reader: call `note(path)` wherever a scan is opened, then
`record("<reader>")` right after writing its output. A reader whose opens
happen in worker processes passes the paths to `record` instead.

Build-time only; never on a request path. Writes data/cards/scan-reads.json
(GENERATED — never hand-edit).
"""
import hashlib
import json
from pathlib import Path

from paths import CARDS_DIR, SCAN_READS

#: the scans opened in this process since it started
_seen = set()


def note(path):
    _seen.add(Path(path).resolve())


def scan_hash(path):
    """the first 16 hex digits of the file's sha256 — the node test's too"""
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()[:16]


def record(reader, paths=None):
    """Replace READER's section with the hash of every scan it read."""
    files = {Path(p).resolve() for p in (paths if paths is not None else _seen)}
    cards = CARDS_DIR.resolve()
    section = {p.name: scan_hash(p) for p in sorted(files) if p.parent == cards and p.exists()}
    try:
        data = json.loads(SCAN_READS.read_text(encoding="utf-8"))
    except FileNotFoundError:
        data = {}
    data["_what"] = ("GENERATED by the bot/pipeline scan readers (scan_reads.py) — never "
                     "hand-edit. For each reader, the sha256 (first 16 hex) of every scan "
                     "it read when it last wrote its output. A scan whose hash differs "
                     "was replaced after the reader ran: re-run that reader.")
    data.setdefault("readers", {})[reader] = section
    data["readers"] = dict(sorted(data["readers"].items()))
    SCAN_READS.write_text(json.dumps(data, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    print(f"recorded {len(section)} scan hashes for {reader} in "
          f"{SCAN_READS.relative_to(CARDS_DIR.parent.parent)}")
